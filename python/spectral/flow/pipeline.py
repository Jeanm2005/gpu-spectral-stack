"""The data pipeline's stages (Task 2.6), driven by params.yaml and run by DVC (dvc.yaml):

    python -m spectral.flow.pipeline generate --params params.yaml --out data/flow.zarr
    python -m spectral.flow.pipeline validate --params params.yaml --data data/flow.zarr \\
        --report reports/validation.json
    python -m spectral.flow.pipeline report --data data/flow.zarr \\
        --validation reports/validation.json --out reports

params.yaml has three sections: `dataset` (a flow.generate.DatasetConfig), `layout` (keyword
arguments of flow.store.create), and `validation` (flow.validate.Thresholds). validate exits 1
when a check fails, which stops `dvc repro` before the report.

The report stage writes the dataset card, reports/DATASET_CARD.md (what the data is, how it was
made, its statistics and validation results), and reports/samples.png.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import yaml

from .generate import DatasetConfig
from .store import EQUATION, open_dataset, write_dataset
from .validate import Thresholds, summary, validate


def load_params(path: Path) -> dict:
    params = yaml.safe_load(Path(path).read_text())
    unknown = set(params) - {"dataset", "layout", "validation"}
    if unknown:
        raise ValueError(f"unknown sections in {path}: {sorted(unknown)}")
    return params


def generate_stage(params: dict, out: Path) -> int:
    config = DatasetConfig.from_dict(params["dataset"])
    ds = write_dataset(out, config, **params.get("layout", {}))
    print(f"wrote {config.num_samples} trajectories to {out} ({ds.attrs['config_hash'][:12]})")
    return 0


def validate_stage(params: dict, data: Path, report_path: Path) -> int:
    thresholds = Thresholds(**params.get("validation", {}))
    report = validate(open_dataset(data), thresholds)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=1) + "\n")
    print(summary(report))
    return 0 if report["passed"] else 1


# --- Dataset card -----------------------------------------------------------------------------


def _snapshot_figure(ds, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    samples = min(4, ds.config.num_samples)
    frames = sorted({0, ds.config.frames // 2, ds.config.frames - 1})
    fig, axes = plt.subplots(
        samples, len(frames), figsize=(2.2 * len(frames), 2.2 * samples), squeeze=False
    )
    for i in range(samples):
        w = ds.vorticity[i]
        limit = float(np.abs(w).max())
        for j, t in enumerate(frames):
            ax = axes[i][j]
            # Diverging data: a two-hue map with a neutral midpoint at zero vorticity.
            ax.imshow(w[t], cmap="RdBu_r", vmin=-limit, vmax=limit, origin="lower")
            ax.set_xticks([])
            ax.set_yticks([])
            if i == 0:
                ax.set_title(f"t = {ds.time[t]:.2f}", fontsize=9)
            if j == 0:
                ax.set_ylabel(f"nu = {ds.viscosity[i]:.1e}", fontsize=8)
    fig.suptitle("Vorticity of the first trajectories (red positive, blue negative)", fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def dataset_card(ds, validation: dict) -> str:
    a, c = ds.attrs, ds.config
    traj = [t for t in validation["trajectories"] if t is not None]
    energy = np.array([t["energy"] for t in traj])
    size_mb = c.num_samples * c.frames * c.n * c.n * 4 / 1e6
    params = validation["checks"]["parameters"]
    lines = [
        f"# Dataset card: flow `{a['config_hash'][:12]}`",
        "",
        "Generated by `dvc repro` (dvc.yaml); this card is rewritten with every dataset version.",
        "",
        "## Contents",
        "",
        f"- {c.num_samples} trajectories of 2D incompressible flow, {c.frames} frames each, "
        f"{c.n} x {c.n} grid, float32 vorticity ({size_mb:.0f} MB)",
        f"- Equation: {EQUATION}",
        f"- Domain: {a['domain']}",
        f"- Forcing A = {c.forcing_amplitude}, k_f = {c.forcing_wavenumber}; drag alpha = {c.drag}",
        f"- Viscosity log-uniform in [{c.viscosity_min:g}, {c.viscosity_max:g}], one per "
        "trajectory",
        f"- Initial vorticity: Gaussian random field, spectrum (|k|^2 + {c.ic_tau:g}^2)^"
        f"(-{c.ic_alpha:g}/2), RMS {c.ic_rms:g}",
        f"- Frames every {c.record_every} steps of dt = {c.dt:g} (every "
        f"{c.record_every * c.dt:g} time units) after {c.spinup_steps} spin-up steps; "
        f"t = {ds.time[0]:.3g} to {ds.time[-1]:.3g}",
        "",
        "## Provenance",
        "",
        f"- Config hash: `{a['config_hash']}`",
        f"- Code: git commit `{a['git_commit']}`",
        f"- Created: {a['created_utc']}",
        f"- Solver: {a['solver']['backend']} backend"
        + (
            f", FFT `{a['solver']['fft_impl']}`, pruned = {a['solver']['pruned']}"
            if a["solver"]["backend"] == "gpu"
            else ""
        )
        + "; IMEX Crank-Nicolson / Heun, 2/3-rule dealiasing",
        f"- Seeds: sample i uses SeedSequence([{c.seed}, i]) (flow.generate.sample_seed)",
        "",
        "## Statistics",
        "",
        "| | min | mean | max |",
        "|---|---:|---:|---:|",
        f"| energy, first frame | {energy[:, 0].min():.4g} | {energy[:, 0].mean():.4g} "
        f"| {energy[:, 0].max():.4g} |",
        f"| energy, last frame | {energy[:, -1].min():.4g} | {energy[:, -1].mean():.4g} "
        f"| {energy[:, -1].max():.4g} |",
        f"| max abs vorticity | {min(t['max_abs_vorticity'] for t in traj):.4g} | "
        f"{np.mean([t['max_abs_vorticity'] for t in traj]):.4g} | "
        f"{max(t['max_abs_vorticity'] for t in traj):.4g} |",
        f"| max CFL number | {min(t['max_cfl'] for t in traj):.3g} | "
        f"{np.mean([t['max_cfl'] for t in traj]):.3g} | {max(t['max_cfl'] for t in traj):.3g} |",
        f"| viscosity | {params['min']:.3g} | {np.mean([t['viscosity'] for t in traj]):.3g} "
        f"| {params['max']:.3g} |",
        "",
        "Viscosity histogram (10 bins in log10): "
        + " ".join(str(h) for h in params["histogram_log10"]),
        "",
        "## Validation",
        "",
        f"**{'Passed' if validation['passed'] else 'Failed'}** "
        "(spectral.flow.validate; thresholds in params.yaml):",
        "",
    ]
    for name, check in validation["checks"].items():
        lines.append(f"- {'passed' if check['passed'] else 'FAILED'}: {name}")
    lines += [
        "",
        "![Vorticity snapshots](samples.png)",
        "",
        "## Intended use",
        "",
        "Training and evaluating neural operators that map vorticity at one time to later times "
        "(Phase 3), read through the streaming loader of Task 2.7. The flows are 2D, periodic, "
        "and forced at one wavenumber: not a model of any particular physical system.",
        "",
    ]
    return "\n".join(lines)


def report_stage(data: Path, validation_path: Path, out: Path) -> int:
    ds = open_dataset(data)
    validation = json.loads(validation_path.read_text())
    out.mkdir(parents=True, exist_ok=True)
    _snapshot_figure(ds, out / "samples.png")
    (out / "DATASET_CARD.md").write_text(dataset_card(ds, validation))
    print(f"wrote {out / 'DATASET_CARD.md'}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m spectral.flow.pipeline",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="stage", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--params", type=Path, required=True)
    g.add_argument("--out", type=Path, required=True)
    v = sub.add_parser("validate")
    v.add_argument("--params", type=Path, required=True)
    v.add_argument("--data", type=Path, required=True)
    v.add_argument("--report", type=Path, required=True)
    r = sub.add_parser("report")
    r.add_argument("--data", type=Path, required=True)
    r.add_argument("--validation", type=Path, required=True)
    r.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)

    if args.stage == "generate":
        return generate_stage(load_params(args.params), args.out)
    if args.stage == "validate":
        return validate_stage(load_params(args.params), args.data, args.report)
    return report_stage(args.data, args.validation, args.out)


if __name__ == "__main__":
    sys.exit(main())
