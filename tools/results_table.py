"""Writes the README's results tables (ours against cuFFT) from the committed benchmark CSVs.

    python tools/results_table.py            # rewrite the tables in README.md
    python tools/results_table.py --check    # fail if README.md is out of date (CI)
    python tools/results_table.py --print    # print the tables only

The tables go between the <!-- results:begin --> and <!-- results:end --> markers in README.md.
Every number comes from docs/results/bench.csv (sizes at a fixed 2^24 points per launch) and
docs/results/bench_batch.csv (fixed sizes over a range of batch counts), so a re-run of the
benchmarks followed by this script is the whole update.

"Speed vs cuFFT" is cuFFT's time divided by ours: above 100 % we are faster.
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- results:begin -->"
END = "<!-- results:end -->"

# Operation -> (title, cuFFT's row label). In the order the tables appear.
OPS = {
    "fft_c2c": ("1D complex (C2C)", "cufft"),
    "fft_r2c": ("1D real to complex (R2C)", "cufft"),
    "fft_c2r": ("1D complex to real (C2R)", "cufft"),
    "fft2_c2c": ("2D complex, n x n", "cufft"),
    "fft2_r2c": ("2D real to complex, n x n", "cufft"),
    "fft2_c2r": ("2D complex to real, n x n", "cufft"),
    "rfft2_modes": ("2D R2C keeping n/8 x n/8 modes (pruned)", "cufft+gather"),
    "irfft2_modes": ("2D C2R from n/8 x n/8 modes (pruned)", "cufft+scatter"),
}


def load(path: Path) -> list[dict]:
    with path.open(newline="") as f:
        lines = [line for line in f if not line.startswith("#")]
    return [
        {
            "op": r["op"],
            "impl": r["impl"],
            "n": int(r["n"]),
            "batch": int(r["batch"]),
            "ms": float(r["time_ms"]),
            "gbps": float(r["gbps"]),
        }
        for r in csv.DictReader(lines)
    ]


def speed(cufft_ms: float, ours_ms: float) -> str:
    return f"{100.0 * cufft_ms / ours_ms:.0f} %"


def best_table(rows: list[dict], op: str, key: str) -> list[str]:
    """One line per (n, batch): cuFFT's time, our fastest implementation, its time and speed."""
    _, baseline = OPS[op]
    groups: dict[tuple[int, int], dict[str, float]] = defaultdict(dict)
    for r in rows:
        if r["op"] == op:
            groups[(r["n"], r["batch"])][r["impl"]] = r["ms"]
    lines = [
        f"| {key} | cuFFT ms | fastest of ours | ms | speed vs cuFFT |",
        "|---:|---:|---|---:|---:|",
    ]
    for (n, batch), times in sorted(groups.items()):
        if baseline not in times:
            continue
        ours = {impl: ms for impl, ms in times.items() if impl != baseline}
        if not ours:
            continue
        impl, ms = min(ours.items(), key=lambda kv: kv[1])
        label = f"{n} x {batch}" if key == "n x batch" else str(n)
        ref_ms = times[baseline]
        lines.append(f"| {label} | {ref_ms:.4f} | {impl} | {ms:.4f} | {speed(ref_ms, ms)} |")
    return lines


def every_impl_table(rows: list[dict], op: str) -> list[str]:
    """Speed vs cuFFT of every one of our implementations, one column each, by size."""
    _, baseline = OPS[op]
    by_n: dict[int, dict[str, float]] = defaultdict(dict)
    impls: list[str] = []
    for r in rows:
        if r["op"] != op:
            continue
        by_n[r["n"]][r["impl"]] = r["ms"]
        if r["impl"] != baseline and r["impl"] not in impls:
            impls.append(r["impl"])
    lines = [
        "| n | " + " | ".join(impls) + " |",
        "|---:|" + "---:|" * len(impls),
    ]
    for n, times in sorted(by_n.items()):
        if baseline not in times:
            continue
        cells = [speed(times[baseline], times[i]) if i in times else "" for i in impls]
        lines.append(f"| {n} | " + " | ".join(cells) + " |")
    return lines


def render(bench: list[dict], batch: list[dict] | None) -> str:
    out = [
        "Speed vs cuFFT is cuFFT's median time divided by ours: above 100 % we are faster. Each "
        "row processes 2^24 points (batch = 2^24 / points per transform) unless it says "
        "otherwise. Generated by `tools/results_table.py` from `docs/results/`.",
        "",
        "#### Every complex 1D implementation, speed vs cuFFT",
        "",
        *every_impl_table(bench, "fft_c2c"),
    ]
    for op, (title, _) in OPS.items():
        if not any(r["op"] == op for r in bench):
            continue
        out += ["", f"#### {title}", "", *best_table(bench, op, "n")]
    if batch:
        out += [
            "",
            "#### By batch: 1D complex at fixed sizes",
            "",
            "Small batches leave most of the GPU idle; there, launch overhead and how fast a "
            "single transform finishes decide.",
            "",
            *best_table(batch, "fft_c2c", "n x batch"),
        ]
    return "\n".join(out) + "\n"


def splice(readme: str, tables: str) -> str:
    if BEGIN not in readme or END not in readme:
        raise ValueError(f"README.md needs the markers {BEGIN} and {END}")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{tables}{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--results", type=Path, default=ROOT / "docs" / "results")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if the README is out of date")
    mode.add_argument("--print", action="store_true", help="print the tables, change nothing")
    args = parser.parse_args(argv)

    bench = load(args.results / "bench.csv")
    batch_path = args.results / "bench_batch.csv"
    batch = load(batch_path) if batch_path.exists() else None
    tables = render(bench, batch)
    if args.print:
        sys.stdout.write(tables)
        return 0

    readme = args.readme.read_text()
    updated = splice(readme, tables)
    if args.check:
        if updated != readme:
            print("README.md results tables are out of date: run python tools/results_table.py")
            return 1
        return 0
    args.readme.write_text(updated)
    print(f"updated the results tables in {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
